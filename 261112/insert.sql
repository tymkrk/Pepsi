CREATE TABLE #inserted (id_override INT NOT NULL PRIMARY KEY);
CREATE TABLE #hook_result (ResultStatus BIT NULL, ResultMessage NVARCHAR(MAX) NULL);
CREATE TABLE #conflicts
(
    source_row INT NOT NULL,
    GPID NVARCHAR(100) NOT NULL,
    conflict_type VARCHAR(20) NOT NULL,
    other_id INT NOT NULL,
    other_start DATE NOT NULL,
    other_end DATE NOT NULL
);

BEGIN TRY
    SELECT @login_user = login_user FROM dbo.k_users WHERE id_user = @id_user;
    IF NULLIF(@login_user, '') IS NULL
        THROW 51001, 'No login_user for the selected id_user.', 1;
    IF NOT EXISTS (SELECT 1 FROM #hr_import)
        THROW 51002, 'Import is empty.', 1;

    -- Reject missing or ambiguous month mappings instead of inventing dates.
    IF EXISTS
    (
        SELECT 1 FROM #hr_import AS i
        WHERE (SELECT COUNT(DISTINCT f.FirstDayOfMonth)
               FROM dbo.vPEPSICO_FiscalMonth_BonusSetup AS f
               WHERE f.YYYYMM = CONVERT(VARCHAR(6), i.start_month)) <> 1
           OR (SELECT COUNT(DISTINCT f.LastDayOfMonth)
               FROM dbo.vPEPSICO_FiscalMonth_BonusSetup AS f
               WHERE f.YYYYMM = CONVERT(VARCHAR(6), i.end_month)) <> 1
    )
        THROW 51003, 'Missing or ambiguous fiscal month mapping. Check active Bonus Setup years.', 1;

    UPDATE i SET
        StartDate = CONVERT(DATE, s.FirstDayOfMonth),
        EndDate = CONVERT(DATE, e.LastDayOfMonth)
    FROM #hr_import AS i
    CROSS APPLY
    (
        SELECT MIN(f.FirstDayOfMonth) AS FirstDayOfMonth
        FROM dbo.vPEPSICO_FiscalMonth_BonusSetup AS f
        WHERE f.YYYYMM = CONVERT(VARCHAR(6), i.start_month)
    ) AS s
    CROSS APPLY
    (
        SELECT MIN(f.LastDayOfMonth) AS LastDayOfMonth
        FROM dbo.vPEPSICO_FiscalMonth_BonusSetup AS f
        WHERE f.YYYYMM = CONVERT(VARCHAR(6), i.end_month)
    ) AS e;

    IF EXISTS (SELECT 1 FROM #hr_import WHERE StartDate IS NULL OR EndDate IS NULL
               OR StartDate > EndDate OR NULLIF(LTRIM(RTRIM(GPID)), '') IS NULL OR LEN(GPID) > 50)
        THROW 51004, 'Invalid GPID or period (post-add accepts GPID up to 50 characters).', 1;

    BEGIN TRANSACTION;

    -- Held until COMMIT: prevent concurrent inserts/updates bypassing the overlap check.
    INSERT INTO #conflicts
    SELECT i.source_row, i.GPID, 'EXISTING', t.idOvrdHRAttributeForBonus, t.StartDate, t.EndDate
    FROM #hr_import AS i
    INNER JOIN dbo.PEPSICO_OvrdHRAttributeForBonus AS t WITH (UPDLOCK, HOLDLOCK)
        ON t.GPID = i.GPID AND t.StartDate <= i.EndDate AND t.EndDate >= i.StartDate;

    INSERT INTO #conflicts
    SELECT a.source_row, a.GPID, 'WITHIN_IMPORT', b.source_row, b.StartDate, b.EndDate
    FROM #hr_import AS a
    INNER JOIN #hr_import AS b
        ON b.GPID = a.GPID AND a.source_row < b.source_row
        AND a.StartDate <= b.EndDate AND a.EndDate >= b.StartDate;

    IF EXISTS (SELECT 1 FROM #conflicts)
    BEGIN
        SELECT source_row, GPID, conflict_type, other_id, other_start, other_end
        FROM #conflicts ORDER BY source_row, other_id;
        THROW 51005, 'Overlapping periods found. Nothing imported; review the conflict result set.', 1;
    END;

    SELECT DB_NAME() AS database_name, @login_user AS import_user,
        COUNT(*) AS row_count, COUNT(DISTINCT GPID) AS gpid_count,
        MIN(StartDate) AS first_start, MAX(EndDate) AS last_end, @apply AS apply_changes
    FROM #hr_import;
    SELECT source_row, GPID, StartDate, EndDate, SalaryAnnualized, AnnualBonusPct,
        PremBonusPct, NonAnnualBonusPct, BDIShortTermTarget, LOAProration,
        Messages, Comments, TransferNextFY
    FROM #hr_import ORDER BY source_row;

    IF @apply = 0
    BEGIN
        ROLLBACK TRANSACTION;
        PRINT 'Validation passed. No business data written. Set @apply = 1 to import.';
        RETURN;
    END;

    INSERT INTO dbo.PEPSICO_OvrdHRAttributeForBonus
        (GPID, StartDate, EndDate, SalaryAnnualized, AnnualBonusPct, PremBonusPct,
         NonAnnualBonusPct, BDIShortTermTarget, LOAProration, Messages, Comments, TransferNextFY)
    OUTPUT inserted.idOvrdHRAttributeForBonus INTO #inserted (id_override)
    SELECT GPID, StartDate, EndDate, SalaryAnnualized, AnnualBonusPct, PremBonusPct,
        NonAnnualBonusPct, BDIShortTermTarget, LOAProration, Messages, Comments, TransferNextFY
    FROM #hr_import;

    -- Post ADD, not Post SAVE: includes audit users, conditional approval reset and refresh queue.
    WHILE 1 = 1
    BEGIN
        SET @primary_key = NULL;
        SELECT @primary_key = MIN(id_override) FROM #inserted WHERE id_override > @last_primary_key;
        IF @primary_key IS NULL BREAK;
        DELETE FROM #hook_result;
        INSERT INTO #hook_result (ResultStatus, ResultMessage)
        EXEC dbo.SP_Grid_Add_Post_PEPSICO_OvrdHRAttributeForBonus
            @UniqueKey = N'', @idUser = @id_user, @idProfile = @id_profile, @primaryKey = @primary_key;
        -- Current hook returns NULL on success; explicit failure must still abort.
        IF EXISTS (SELECT 1 FROM #hook_result WHERE ResultStatus = 0)
        BEGIN
            SELECT @primary_key AS id_override, ResultStatus, ResultMessage FROM #hook_result;
            THROW 51006, 'Post-add returned failure. Import rolled back.', 1;
        END;
        SET @last_primary_key = @primary_key;
    END;

    -- Snapshot after post-add so audit users are populated. History is not written by the hook.
    INSERT INTO dbo.PEPSICO_OvrdHRAttributeForBonus_xhisto
        (id_user_xhisto, dt_xhisto, type_xhisto, idOvrdHRAttributeForBonus,
         GPID, StartDate, EndDate, SalaryAnnualized, AnnualBonusPct, PremBonusPct,
         NonAnnualBonusPct, BDIShortTermTarget, LOAProration, Messages, Comments,
         TransferNextFY, InsertTime, InsertUser, UpdateTime, UpdateUser)
    SELECT -1, GETUTCDATE(), 'ins', t.idOvrdHRAttributeForBonus,
        t.GPID, t.StartDate, t.EndDate, t.SalaryAnnualized, t.AnnualBonusPct, t.PremBonusPct,
        t.NonAnnualBonusPct, t.BDIShortTermTarget, t.LOAProration, t.Messages, t.Comments,
        t.TransferNextFY, t.InsertTime, t.InsertUser, t.UpdateTime, t.UpdateUser
    FROM dbo.PEPSICO_OvrdHRAttributeForBonus AS t
    INNER JOIN #inserted AS i ON i.id_override = t.idOvrdHRAttributeForBonus;

    COMMIT TRANSACTION;
    SELECT id_override AS inserted_id FROM #inserted ORDER BY id_override;
    PRINT 'Import committed. Post-add queued refresh requests; scheduler execution is separate.';
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
